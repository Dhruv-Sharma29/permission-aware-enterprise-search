"""Role-dependent demo: the same questions, asked by different users, through the API.

    python -m eval.role_demo        # needs the ingested corpus (python -m search.ingest .run/corpus)

Each user gets a real bearer token (identity.tokens.issue) and calls /search and /answer the way a
client would (FastAPI TestClient, in process). The questions are chosen by the independent oracle,
not by the system: those whose gold documents some demo users can read and others can't. For every
(question, user) the run checks that every search result and citation is readable by that user and
that no value found only in documents the user can't read appears in the answer, then records
whether the answer is supported by a readable gold document or the service abstained.

Writes results/summary/role_demo.json and role_demo.md. Exits non-zero on any leak.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

from fastapi.testclient import TestClient

from identity.oracle import Oracle
from identity.tokens import issue
from search.api import app

ROOT = Path(__file__).resolve().parents[1]
CORPUS = ROOT / ".run/corpus"
# One user per access pattern that matters: engineer, HR, HR + engineering managers, finance +
# executives, and a contractor who belongs to no group and sees only documents shared by name.
USERS = ["alice", "carol", "judy", "lena", "ken"]
PREFERRED = ["role-conflicting", "shared-by-name", "confidential-scanned", "confidential", "overlapping"]
MAX_QUESTIONS = 6


def pick_questions(oracle: Oracle, questions: list[dict]) -> list[dict]:
    """Questions whose answerability differs across USERS, one per distinct access pattern, most
    telling categories first."""
    chosen, seen = [], set()
    for q in sorted(questions, key=lambda q: (PREFERRED.index(q["category"]) if q["category"] in PREFERRED
                                              else len(PREFERRED), q["qid"])):
        pattern = tuple(any(oracle.can_read(u, d) for d in q["gold_docs"]) for u in USERS)
        if q["category"] in PREFERRED and len(set(pattern)) > 1 and pattern not in seen:
            chosen.append(q)
            seen.add(pattern)
        if len(chosen) == MAX_QUESTIONS:
            break
    return chosen


def main() -> int:
    oracle = Oracle(CORPUS)
    questions = pick_questions(oracle, json.loads((CORPUS / "questions.json").read_text()))
    forbidden = {u: oracle.forbidden_values(u) for u in USERS}
    api = TestClient(app)
    rows, leaks = [], 0
    for q in questions:
        for u in USERS:
            headers = {"Authorization": f"Bearer {issue(u)}"}
            results = api.post("/search", json={"query": q["text"]}, headers=headers).json()["results"]
            answer = api.post("/answer", json={"query": q["text"]}, headers=headers).json()
            text = answer.get("answer") or ""
            readable_gold = [d for d in q["gold_docs"] if oracle.can_read(u, d)]
            row = {
                "qid": q["qid"], "category": q["category"], "question": q["text"], "user": u,
                "can_read_gold": bool(readable_gold),
                "top_results": [r["title"] for r in results[:3]],
                "abstained": answer["abstained"], "answer": text or None,
                "cited": [c["title"] for c in answer["citations"]],
                "supported": not answer["abstained"] and any(a in text for a in q["answers"]),
                "result_leaks": sum(not oracle.can_read(u, r["doc_id"]) for r in results),
                "citation_leaks": sum(not oracle.can_read(u, c["doc_id"]) for c in answer["citations"]),
                "content_leaks": sum(v in text for v in forbidden[u]),
            }
            leaks += row["result_leaks"] + row["citation_leaks"] + row["content_leaks"]
            rows.append(row)

    summary = {
        "users": USERS, "questions": len(questions), "pairs": len(rows), "leaks": leaks,
        "answerable_pairs": sum(r["can_read_gold"] for r in rows),
        "supported_when_answerable": sum(r["supported"] for r in rows if r["can_read_gold"]),
        "abstained_when_not_answerable": sum(r["abstained"] for r in rows if not r["can_read_gold"]),
        "answered_when_not_answerable": sum(not r["abstained"] for r in rows if not r["can_read_gold"]),
        "threshold": "service default (results/summary/eval.json chosen_threshold)",
    }
    out = ROOT / "results/summary"
    (out / "role_demo.json").write_text(json.dumps({"summary": summary, "rows": rows}, indent=1) + "\n")
    (out / "role_demo.md").write_text(render(summary, questions, rows))
    print(json.dumps(summary, indent=1))
    return 1 if leaks else 0


def render(summary: dict, questions: list[dict], rows: list[dict]) -> str:
    lines = ["# Role-dependent demo: same question, different users", "",
             "Generated by `python -m eval.role_demo`. Every result and citation checked against the "
             "independent oracle (`identity/oracle.py`).", "",
             f"- Pairs: {summary['pairs']} ({summary['questions']} questions x {len(summary['users'])} users); "
             f"leaks: **{summary['leaks']}**",
             f"- Answerable for the user: {summary['answerable_pairs']}; supported answer: "
             f"{summary['supported_when_answerable']}",
             f"- Not answerable for the user: {summary['pairs'] - summary['answerable_pairs']}; abstained: "
             f"{summary['abstained_when_not_answerable']}, answered anyway (from other readable documents): "
             f"{summary['answered_when_not_answerable']}", ""]
    for q in questions:
        lines += [f"## {q['qid']} ({q['category']}): {q['text']}", "",
                  "| User | Can read the answer's source | Answer | Cited | Top search result |",
                  "|---|---|---|---|---|"]
        for r in (r for r in rows if r["qid"] == q["qid"]):
            ans = "*abstained*" if r["abstained"] else (r["answer"] or "").replace("|", "\\|")[:110]
            lines.append(f"| {r['user']} | {'yes' if r['can_read_gold'] else 'no'} | {ans} | "
                         f"{'; '.join(r['cited']) or '—'} | {r['top_results'][0] if r['top_results'] else '—'} |")
        lines.append("")
    return "\n".join(lines)


if __name__ == "__main__":
    sys.exit(main())
